def rendered_files(root: Path) -> dict[str, str]:
    findings_data = load_json(root / "findings.json")
    coverage_data = load_json(root / "coverage.json")
    return {
        "09-implementation-sequence.md": render_implementation(findings_data),
        "10-review-coverage.md": render_coverage(coverage_data, findings_data),
        "11-findings-register.md": render_findings(findings_data),
    }


def render_to_disk(root: Path) -> None:
    for name, content in rendered_files(root).items():
        (root / name).write_text(content, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("teardown", type=Path, help="Path to the seo-teardown directory")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check generated files without writing them",
    )
    args = parser.parse_args()
    root = args.teardown.resolve()
    expected = rendered_files(root)
    if args.check:
        mismatches = []
        for name, content in expected.items():
            path = root / name
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                mismatches.append(name)
        if mismatches:
            print("Generated handoff files are stale or missing:")
            for name in mismatches:
                print(f"- {name}")
            return 1
        print("Generated handoff files match canonical JSON")
        return 0
    for name, content in expected.items():
        (root / name).write_text(content, encoding="utf-8")
        print(f"Rendered {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
