#!/usr/bin/env python3
"""Render deterministic Markdown registers from an SEO teardown's canonical JSON."""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any

GENERATED_NOTICE = "<!-- Generated by seo-teardown/scripts/render_handoff.py. Do not edit directly. -->"


def load_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
    if not isinstance(data, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return data


def text(value: Any) -> str:
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int, float)):
        return str(value)
    value = str(value).strip()
    return value or "None"


def inline_list(values: Any) -> str:
    if values is None:
        return "None"
    if not isinstance(values, list):
        return text(values)
    if not values:
        return "None"
    return ", ".join(text(item) for item in values)


def bullet_list(values: Any, indent: str = "") -> list[str]:
    if not isinstance(values, list) or not values:
        return [f"{indent}- None"]
    return [f"{indent}- {text(item)}" for item in values]


def md_cell(value: Any) -> str:
    return text(value).replace("|", "\\|").replace("\n", "<br>")


def render_implementation(findings_data: dict[str, Any]) -> str:
    findings = {item["id"]: item for item in findings_data.get("findings", [])}
    audit = findings_data.get("audit", {})
    lines = [
        GENERATED_NOTICE,
        "",
        "# Implementation sequence",
        "",
        f"**Review status:** {text(audit.get('review_status'))}",
        "",
        "The sequence is dependency-aware. Finding order is canonical in `findings.json`.",
        "",
    ]

    for phase in findings_data.get("implementation_phases", []):
        lines.extend(
            [
                f"## {text(phase.get('id'))} — {text(phase.get('title'))}",
                "",
                f"**Rationale:** {text(phase.get('rationale'))}",
                "",
                f"**Validation gate:** {text(phase.get('validation_gate'))}",
                "",
                f"**Expected outcome:** {text(phase.get('expected_outcome'))}",
                "",
                "| Finding | Order | Disposition | Severity | Status | Dependencies | Rationale |",
                "|---|---:|---|---|---|---|---|",
            ]
        )
        phase_findings = [findings[fid] for fid in phase.get("finding_ids", []) if fid in findings]
        phase_findings.sort(key=lambda item: item.get("implementation", {}).get("order", 0))
        for finding in phase_findings:
            implementation = finding.get("implementation", {})
            deps = finding.get("dependencies", [])
            lines.append(
                "| {id} | {order} | {disposition} | {severity} | {status} | {deps} | {rationale} |".format(
                    id=md_cell(finding.get("id")),
                    order=md_cell(implementation.get("order")),
                    disposition=md_cell(implementation.get("disposition")),
                    severity=md_cell(finding.get("severity")),
                    status=md_cell(finding.get("status")),
                    deps=md_cell(inline_list(deps)),
                    rationale=md_cell(implementation.get("rationale")),
                )
            )
        lines.append("")

    lines.extend(["## Complete finding ledger", "", "Every finding appears exactly once below.", ""])
    ordered = sorted(
        findings.values(), key=lambda item: item.get("implementation", {}).get("order", 0)
    )
    for finding in ordered:
        impl = finding.get("implementation", {})
        lines.append(
            f"- {finding.get('id')} — phase {impl.get('phase_id')}, order {impl.get('order')}, "
            f"disposition {impl.get('disposition')}"
        )
    lines.append("")
    return "\n".join(lines)


def render_serp_winners(item: dict[str, Any]) -> str:
    winner = item.get("winner_observation", {})
    status = winner.get("status")
    if status == "observed":
        parts = []
        for result in winner.get("results", []):
            value = text(result.get("value"))
            position = text(result.get("position"))
            parts.append(f"{value} ({position})")
        return inline_list(parts)
    return f"{text(status)} — {text(winner.get('reason'))}"


def render_method_evidence(item: dict[str, Any]) -> str:
    parts = []
    for method in item.get("method_evidence", []):
        parts.append(
            f"{text(method.get('method'))}={text(method.get('status'))}: "
            f"{text(method.get('observation'))} [evidence: {inline_list(method.get('evidence_ids'))}; "
            f"limits: {inline_list(method.get('limitations'))}]"
        )
    return inline_list(parts)


def render_url_observation(item: dict[str, Any], key: str) -> str:
    observation = item.get(key, {})
    status = text(observation.get("status"))
    value = observation.get("value")
    rendered_value = "None" if value is None else text(value)
    return (
        f"{status}: {rendered_value}; methods={inline_list(observation.get('supported_by_methods'))}; "
        f"evidence={inline_list(observation.get('evidence_ids'))}; "
        f"limits={inline_list(observation.get('limitations'))}"
    )


def render_coverage(coverage_data: dict[str, Any], findings_data: dict[str, Any]) -> str:
    findings = findings_data.get("findings", [])
    evidence = findings_data.get("evidence_sources", [])
    severity_counts = Counter(item.get("severity") for item in findings)
    status_counts = Counter(item.get("status") for item in findings)
    kind_counts = Counter(item.get("kind") for item in findings)

    lines = [
        GENERATED_NOTICE,
        "",
        "# Review coverage",
        "",
        f"**Review status:** {text(coverage_data.get('review_status'))}",
        "",
        "## Evidence and access ledger",
        "",
        "| Access category | Status | Coverage window | Material to comprehensive | Evidence | Limitations | Next step |",
        "|---|---|---|---|---|---|---|",
    ]
    for item in coverage_data.get("access", []):
        lines.append(
            "| {category} | {status} | {window} | {material} | {evidence} | {limits} | {next_step} |".format(
                category=md_cell(item.get("category")),
                status=md_cell(item.get("status")),
                window=md_cell(item.get("coverage_window")),
                material=md_cell(item.get("material_to_comprehensive")),
                evidence=md_cell(inline_list(item.get("evidence_ids"))),
                limits=md_cell(inline_list(item.get("limitations"))),
                next_step=md_cell(item.get("next_step")),
            )
        )

    lines.extend(
        [
            "",
            "## Audit module ledger",
            "",
            "| Module | Applicable | Materiality | Status | Findings | Evidence | Limitations | Next step |",
            "|---|---|---|---|---|---|---|---|",
        ]
    )
    for item in coverage_data.get("modules", []):
        lines.append(
            "| {module} | {applicable} | {materiality} | {status} | {checks} | {findings} | {evidence} | {limits} | {next_step} |".format(
                module=md_cell(item.get("id")),
                applicable=md_cell(item.get("applicable")),
                materiality=md_cell(item.get("materiality")),
                status=md_cell(item.get("status")),
                checks=md_cell(inline_list(item.get("check_ids"))),
                findings=md_cell(inline_list(item.get("finding_ids"))),
                evidence=md_cell(inline_list(item.get("evidence_ids"))),
                limits=md_cell(inline_list(item.get("limitations"))),
                next_step=md_cell(item.get("next_step")),
            )
        )

    lines.extend([
        "",
        "## Surface check ledger",
        "",
        "| Check | Module | Facet | Method | Status | Findings | Evidence | Available work completed | Result | Unknowns | Limitation refs | Limitations |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ])
    for item in coverage_data.get("surface_checks", []):
        lines.append(
            "| {id} | {module} | {facet} | {method} | {status} | {findings} | {evidence} | {completed} | {result} | {unknowns} | {refs} | {limits} |".format(
                id=md_cell(item.get("id")), module=md_cell(item.get("module_id")),
                facet=md_cell(item.get("facet")), method=md_cell(item.get("method")),
                status=md_cell(item.get("status")), findings=md_cell(inline_list(item.get("finding_ids"))),
                evidence=md_cell(inline_list(item.get("evidence_ids"))), completed=md_cell(item.get("available_work_completed")),
                result=md_cell(item.get("result")), unknowns=md_cell(inline_list(item.get("unknowns"))),
                refs=md_cell(inline_list(item.get("limitation_refs"))), limits=md_cell(inline_list(item.get("limitations"))),
            )
        )

    lines.extend([
        "",
        "## SERP sample ledger",
        "",
        "| Sample | Query | Surface | Location | Device | Observed | Features | Winners | Target | Evidence | Limitations |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ])
    for item in coverage_data.get("serp_samples", []):
        lines.append(
            "| {id} | {query} | {surface} | {location} | {device} | {date} | {features} | {winners} | {target} | {evidence} | {limits} |".format(
                id=md_cell(item.get("id")), query=md_cell(item.get("query")), surface=md_cell(item.get("engine_or_surface")),
                location=md_cell(item.get("location")), device=md_cell(item.get("device")), date=md_cell(item.get("observed_at")),
                features=md_cell(inline_list(item.get("result_features"))), winners=md_cell(render_serp_winners(item)),
                target=md_cell(item.get("target_observation")), evidence=md_cell(inline_list(item.get("evidence_ids"))),
                limits=md_cell(inline_list(item.get("limitations"))),
            )
        )

    lines.extend([
        "",
        "## URL sample ledger",
        "",
        "| Sample | URL | Role | Method evidence | Revision alignment | HTTP observation | Eligibility observation | Index observation | Canonical observation | Render observation | Findings | Evidence | Limitations |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ])
    for item in coverage_data.get("url_samples", []):
        lines.append(
            "| {id} | {url} | {role} | {methods} | {alignment} | {http} | {eligibility} | {index_state} | {canonical} | {render} | {findings} | {evidence} | {limits} |".format(
                id=md_cell(item.get("id")), url=md_cell(item.get("url")), role=md_cell(item.get("role")),
                methods=md_cell(render_method_evidence(item)), alignment=md_cell(item.get("source_revision_alignment")),
                http=md_cell(render_url_observation(item, "http_observation")),
                eligibility=md_cell(render_url_observation(item, "eligibility_observation")),
                index_state=md_cell(render_url_observation(item, "index_observation")),
                canonical=md_cell(render_url_observation(item, "canonical_observation")),
                render=md_cell(render_url_observation(item, "render_observation")), findings=md_cell(inline_list(item.get("finding_ids"))),
                evidence=md_cell(inline_list(item.get("evidence_ids"))), limits=md_cell(inline_list(item.get("limitations"))),
            )
        )

    lines.extend(["", "## Deliberate non-pursuits", ""])
    for item in coverage_data.get("deliberate_non_pursuits", []):
        lines.append(f"- **{text(item.get('topic'))}:** {text(item.get('rationale'))} (evidence: {inline_list(item.get('evidence_ids'))})")
    if not coverage_data.get("deliberate_non_pursuits"):
        lines.append("- None")

    lines.extend(["", "## Material limitations", ""])
    limitations = coverage_data.get("material_limitations", [])
    if limitations:
        for item in limitations:
            if isinstance(item, dict):
                lines.append(
                    f"- **{text(item.get('id'))}:** {text(item.get('description'))} "
                    f"(status: {text(item.get('status'))}; completion requirement: "
                    f"{text(item.get('completion_requirement'))})"
                )
            else:
                lines.append(f"- {text(item)}")
    else:
        lines.append("- None")

    lines.extend(["", "## Narrative reconciliation", ""])
    reconciliation = coverage_data.get("narrative_reconciliation", [])
    lines.extend(
        [
            "| Narrative location | Finding IDs | Non-actionable explanation |",
            "|---|---|---|",
        ]
    )
    for item in reconciliation:
        lines.append(
            "| {location} | {ids} | {explanation} |".format(
                location=md_cell(item.get("location")),
                ids=md_cell(inline_list(item.get("finding_ids"))),
                explanation=md_cell(item.get("non_actionable_explanation")),
            )
        )

    lines.extend(
        [
            "",
            "## Counts",
            "",
            f"- Evidence sources: {len(evidence)}",
            f"- Findings: {len(findings)}",
            f"- Severity: {', '.join(f'{key}={value}' for key, value in sorted(severity_counts.items())) or 'None'}",
            f"- Status: {', '.join(f'{key}={value}' for key, value in sorted(status_counts.items())) or 'None'}",
            f"- Kind: {', '.join(f'{key}={value}' for key, value in sorted(kind_counts.items())) or 'None'}",
            "",
            "## Validator",
            "",
        ]
    )
    validator = coverage_data.get("validator", {})
    lines.extend(
        [
            f"- **Command:** `{text(validator.get('command'))}`",
            f"- **Recorded result:** {text(validator.get('result'))}",
            "",
        ]
    )
    return "\n".join(lines)


