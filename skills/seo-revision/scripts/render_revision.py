#!/usr/bin/env python3
"""Render deterministic Markdown registers from canonical seo-revision JSON."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


NOTICE = "<!-- Generated by seo-revision/scripts/render_revision.py. Do not edit directly. -->"


def load_revision(root: Path) -> dict[str, Any]:
    value = json.loads((root / "revision.json").read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError("revision.json must contain an object")
    return value


def text(value: Any) -> str:
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int, float)):
        return str(value)
    value = str(value).strip()
    return value or "None"


def inline(values: Any) -> str:
    if not isinstance(values, list) or not values:
        return "None"
    return ", ".join(text(item) for item in values)


def cell(value: Any) -> str:
    return text(value).replace("|", "\\|").replace("\n", "<br>")


def bullets(values: Any) -> list[str]:
    if not isinstance(values, list) or not values:
        return ["- None"]
    return [f"- {text(item)}" for item in values]


def header(title: str) -> list[str]:
    return [NOTICE, "", f"# {title}", ""]


def render_decisions(data: dict[str, Any]) -> str:
    teardown = data.get("teardown", {})
    lines = header("Decisions, authority, and scope")
    lines.extend(
        [
            f"**Mode:** {text(data.get('mode'))}",
            f"**Project:** {text(data.get('project', {}).get('name'))}",
            f"**Teardown path:** {text(teardown.get('path'))}",
            f"**Teardown findings schema:** {text(teardown.get('findings_schema'))}",
            f"**Teardown coverage schema:** {text(teardown.get('coverage_schema'))}",
            f"**Teardown review status:** {text(teardown.get('review_status'))}",
            f"**Upstream validator:** {text(teardown.get('validator_result'))}",
            "",
            "## Owner decision packet",
            "",
        ]
    )
    decisions = data.get("decisions", [])
    if not decisions:
        lines.append("None")
    for decision in decisions:
        lines.extend(
            [
                f"### {text(decision.get('id'))} — {text(decision.get('question'))}",
                "",
                f"- **Findings:** {inline(decision.get('finding_ids'))}",
                f"- **Status:** {text(decision.get('status'))}",
                f"- **Recommendation:** {text(decision.get('recommendation'))}",
                f"- **Owner selection:** {text(decision.get('owner_selection'))}",
                f"- **Safe default:** {text(decision.get('safe_default'))}",
                f"- **Consequences:** {inline(decision.get('consequences'))}",
                f"- **Prerequisites:** {inline(decision.get('prerequisites'))}",
                f"- **Reversibility:** {text(decision.get('reversibility'))}",
                "",
                "| Option | Label | Consequences | Prerequisites | Reversibility |",
                "|---|---|---|---|---|",
            ]
        )
        for option in decision.get("options", []):
            lines.append(
                f"| {cell(option.get('id'))} | {cell(option.get('label'))} | "
                f"{cell(inline(option.get('consequences')))} | "
                f"{cell(inline(option.get('prerequisites')))} | "
                f"{cell(option.get('reversibility'))} |"
            )
        lines.append("")

    lines.extend(
        [
            "## Authority matrix",
            "",
            "| Authority | State | Scope | Evidence | Limitations |",
            "|---|---|---|---|---|",
        ]
    )
    for item in data.get("authority_matrix", []):
        lines.append(
            f"| {cell(item.get('id'))} | {cell(item.get('state'))} | "
            f"{cell(item.get('scope'))} | {cell(inline(item.get('evidence_ids')))} | "
            f"{cell(inline(item.get('limitations')))} |"
        )
    lines.extend(["", "## Finding approval matrix", "", "| Finding | Approval | Revalidation | Disposition |", "|---|---|---|---|"])
    for finding in sorted(data.get("findings", []), key=lambda x: x.get("sequence", 0)):
        lines.append(
            f"| {cell(finding.get('id'))} | {cell(finding.get('approval'))} | "
            f"{cell(finding.get('revalidation'))} | {cell(finding.get('disposition'))} |"
        )
    lines.append("")
    return "\n".join(lines)


