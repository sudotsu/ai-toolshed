def render_readiness(data: dict[str, Any]) -> str:
    readiness = data.get("readiness", {})
    workspace = data.get("workspace", {})
    delivery = readiness.get("delivery", {})
    lines = header("Readiness and handoff")
    lines.extend(
        [
            f"**Revision status:** {text(readiness.get('revision_status'))}",
            f"**Product endpoint:** {text(workspace.get('product_endpoint'))}",
            f"**Artifact relationship:** {text(workspace.get('artifact_relationship'))}",
            f"**Review convergence:** {text(readiness.get('review_convergence'))}",
            f"**Integration readiness:** {text(readiness.get('integration'))}",
            f"**Deployment readiness:** {text(readiness.get('deployment'))}",
            f"**Publication readiness:** {text(readiness.get('publication'))}",
            f"**Search validation:** {text(readiness.get('search_validation'))}",
            f"**Experiment status:** {text(readiness.get('experiment_status'))}",
            f"**Authorization summary:** {text(readiness.get('authorization_summary'))}",
            f"**Convergence evidence:** {inline(readiness.get('convergence_evidence_ids'))}",
            "",
            "## Delivery facts",
            "",
            "| Delivery action | State |",
            "|---|---|",
        ]
    )
    for key in (
        "committed",
        "pushed",
        "pull_request",
        "merged",
        "deployed",
        "published",
        "search_platform_actions",
        "external_profile_actions",
    ):
        item = delivery.get(key, {})
        lines.append(
            f"| {key.replace('_', ' ').title()} | {cell(item.get('state'))}; "
            f"evidence={cell(inline(item.get('evidence_ids')))}; "
            f"{cell(item.get('observation'))} |"
        )
    lines.extend(["", "## Unverified outcomes", ""])
    lines.extend(bullets(readiness.get("unverified_outcomes")))
    lines.extend(["", "## Follow-up actions", ""])
    lines.extend(bullets(readiness.get("follow_up_actions")))
    lines.extend(
        [
            "",
            "## Counts",
            "",
            f"- Teardown findings: {len(data.get('findings', []))}",
            f"- Recorded changes: {len(data.get('changes', []))}",
            f"- Convergence findings: {len(data.get('convergence_findings', []))}",
            f"- Evidence records: {len(data.get('evidence', []))}",
            f"- URL verifications: {len(data.get('url_verifications', []))}",
            f"- Experiments: {len(data.get('experiments', []))}",
            "",
        ]
    )
    return "\n".join(lines)


def rendered_files(root: Path) -> dict[str, str]:
    data = load_revision(root)
    return {
        "00-decisions-authority-and-scope.md": render_decisions(data),
        "01-baseline-drift-and-revalidation.md": render_baseline(data),
        "02-execution-rollout-and-measurement-plan.md": render_plan(data),
        "03-implementation-ledger.md": render_implementation(data),
        "04-convergence-ledger.md": render_convergence(data),
        "05-production-search-and-experiment-verification.md": render_verification(data),
        "06-readiness-and-handoff.md": render_readiness(data),
    }


def render_to_disk(root: Path) -> None:
    for name, content in rendered_files(root).items():
        (root / name).write_text(content, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("revision", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.revision.resolve()
    expected = rendered_files(root)
    if args.check:
        mismatches = [
            name
            for name, content in expected.items()
            if not (root / name).is_file()
            or (root / name).read_text(encoding="utf-8") != content
        ]
        if mismatches:
            print("Generated revision files are stale or missing:")
            for name in mismatches:
                print(f"- {name}")
            return 1
        print("Generated revision files match canonical JSON")
        return 0
    for name, content in expected.items():
        (root / name).write_text(content, encoding="utf-8")
        print(f"Rendered {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
