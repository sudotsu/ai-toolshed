def render_implementation(data: dict[str, Any]) -> str:
    change_map = {item.get("id"): item for item in data.get("changes", [])}
    title = (
        "Implementation ledger"
        if data.get("mode") == "implementation"
        else "Implementation ledger (planning-only — no implementation performed)"
    )
    lines = header(title)
    lines.append(
        "Every teardown finding appears exactly once below. "
        + (
            "The records describe completed or blocked execution."
            if data.get("mode") == "implementation"
            else "All executable work remains a plan or explicit blocker; no product change is claimed."
        )
    )
    lines.append("")
    for finding in sorted(data.get("findings", []), key=lambda x: x.get("sequence", 0)):
        lines.extend(
            [
                f"## {text(finding.get('id'))} — {text(finding.get('title'))}",
                "",
                f"- **Approval:** {text(finding.get('approval'))}",
                f"- **Revalidation:** {text(finding.get('revalidation'))}",
                f"- **Disposition:** {text(finding.get('disposition'))}",
                f"- **Sequence:** {text(finding.get('sequence'))}",
                f"- **Dependencies:** {inline(finding.get('dependencies'))}",
                f"- **Reason:** {text(finding.get('reason'))}",
                f"- **Evidence:** {inline(finding.get('evidence_ids'))}",
                f"- **Changes:** {inline(finding.get('change_ids'))}",
                f"- **Experiments:** {inline(finding.get('experiment_ids'))}",
                f"- **Completion gates:** {inline(finding.get('completion_gates'))}",
                f"- **Notes:** {inline(finding.get('notes'))}",
                "",
                "### Acceptance results",
                "",
                "| Criterion | Status | Evidence | Observation |",
                "|---|---|---|---|",
            ]
        )
        for result in finding.get("acceptance_results", []):
            lines.append(
                f"| {cell(result.get('criterion'))} | {cell(result.get('status'))} | "
                f"{cell(inline(result.get('evidence_ids')))} | {cell(result.get('observation'))} |"
            )
        lines.extend(["", "### Mapped changes", ""])
        for change_id in finding.get("change_ids", []):
            change = change_map.get(change_id, {})
            lines.append(
                f"- **{change_id}:** {text(change.get('description'))}; "
                f"targets={inline(change.get('targets'))}; risk={text(change.get('risk_level'))}"
            )
        if not finding.get("change_ids"):
            lines.append("- None")
        lines.append("")

    lines.extend(["# Change inventory", ""])
    for change in data.get("changes", []):
        lines.extend(
            [
                f"### {text(change.get('id'))} — {text(change.get('description'))}",
                "",
                f"- **Scope:** {text(change.get('scope'))}",
                f"- **Findings:** {inline(change.get('finding_ids'))}",
                f"- **Convergence:** {inline(change.get('convergence_ids'))}",
                f"- **Targets:** {inline(change.get('targets'))}",
                f"- **External authorities:** {inline(change.get('external_authority_ids'))}",
                f"- **Risk:** {text(change.get('risk_level'))} — {inline(change.get('risk_categories'))}",
                f"- **Rollout:** {text(change.get('rollout_id'))}",
                f"- **Evidence:** {inline(change.get('evidence_ids'))}",
                "",
            ]
        )
    if not data.get("changes"):
        lines.append("None — no implementation changes recorded.")
    lines.append("")
    return "\n".join(lines)


